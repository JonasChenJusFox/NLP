import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = file => readFile(path.join(root, file), 'utf8');
function inlineModule(source) {
  return source
    .replace(/^import .*? from ['"].*?['"];?\r?\n/gm, '')
    .replace(/^export \{[^\n]*\} from ['"][^\n]+\r?\n/gm, '')
    .replace(/^export (?=(?:const|function|class)\b)/gm, '');
}
const [unicode, text, model, worker, data] = await Promise.all([
  read('edge/unicode.mjs'), read('edge/text.mjs'), read('edge/model.mjs'), read('worker/index.js'), read('edge/model-data.json')
]);
const parsed = JSON.parse(data);
if (parsed.model_id !== '9439f39e3b9e7f45') throw new Error('Frozen model ID changed; review the export before building.');
const assets = {};
for (const [file, type] of [['index.html', 'text/html'], ['style.css', 'text/css'], ['app.js', 'text/javascript']]) {
  assets[file === 'index.html' ? '/' : `/${file}`] = { body: await read(`public/${file}`), type: `${type}; charset=utf-8` };
}
const bundled = `// Frozen SMS Spam Robustness model ${parsed.model_id}. Generated by scripts/build.mjs.\n
const unicode = (() => {\n${inlineModule(unicode)}\nreturn {PYTHON_WORD_CLASS, PYTHON_DIGIT_CLASS, pythonLower};})();
const text = (({PYTHON_WORD_CLASS, PYTHON_DIGIT_CLASS, pythonLower}) => {\n${inlineModule(text)}\nreturn {createTextProcessor, METHODS, PYTHON_WORD_CLASS, pythonLower};})(unicode);
const model = (({PYTHON_WORD_CLASS, pythonLower}) => {\n${inlineModule(model)}\nreturn {createPredictor};})(text);
const application = (({createPredictor}, {createTextProcessor, METHODS}) => {\n${inlineModule(worker)}\nreturn {createWorker};})(model, text);
const modelJSON = ${JSON.stringify(data)};
const assets = ${JSON.stringify(assets)};
const site = application.createWorker(() => JSON.parse(modelJSON), assets);
export default site;
`;
if (/^import\s|^export \{/m.test(bundled)) throw new Error('An unbundled module import/export remains.');
const dist = path.join(root, 'dist');
await rm(dist, { recursive: true, force: true });
await mkdir(path.join(dist, 'server'), { recursive: true });
await writeFile(path.join(dist, 'server/index.js'), bundled);
const manifest = {
  model_id: parsed.model_id,
  model_data_sha256: createHash('sha256').update(data).digest('hex'),
  worker_sha256: createHash('sha256').update(bundled).digest('hex'),
  worker_bytes: Buffer.byteLength(bundled),
  runtime: 'Cloudflare Workers ESM',
  external_runtime_dependencies: []
};
await writeFile(path.join(dist, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify(manifest));
