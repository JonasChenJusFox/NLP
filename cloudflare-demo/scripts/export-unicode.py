"""Export frozen-runtime Unicode semantics; run with the model's Python venv."""
import json
import unicodedata
from pathlib import Path


def character_class(codepoints):
    ranges = []
    start = previous = None
    for number in codepoints:
        if start is None:
            start = previous = number
        elif number == previous + 1:
            previous = number
        else:
            ranges.append((start, previous))
            start = previous = number
    if start is not None:
        ranges.append((start, previous))
    escape = lambda value: r"\u{%x}" % value
    return "[" + "".join(escape(a) if a == b else escape(a) + "-" + escape(b)
                         for a, b in ranges) + "]"


def main():
    word, digit, cased, ignorable = [], [], [], []
    lower = {}
    for number in range(0x110000):
        char = chr(number)
        if char.isalnum() or char == "_":
            word.append(number)
        if char.isdecimal():
            digit.append(number)
        lowered = char.lower()
        if lowered != char:
            lower[char] = lowered
        is_cased = char.islower() or char.isupper() or char.istitle()
        if is_cased:
            cased.append(number)
            # An ignorable character cannot supply the preceding cased letter
            # that would make the final capital sigma lowercase to final sigma.
            is_ignorable = (" " + char + "Σ").lower()[-1] == "σ"
        else:
            # If ignored, the following A prevents a final sigma.
            is_ignorable = ("AΣ" + char + "A").lower()[1] == "σ"
        if is_ignorable:
            ignorable.append(number)
    target = Path(__file__).resolve().parents[1] / "edge/unicode.mjs"
    content = "// Generated by scripts/export-unicode.py; Unicode %s.\n" % unicodedata.unidata_version
    for name, values in [("PYTHON_WORD_CLASS", word), ("PYTHON_DIGIT_CLASS", digit),
                         ("PYTHON_CASED_CLASS", cased), ("PYTHON_CASE_IGNORABLE_CLASS", ignorable)]:
        content += "export const %s = %s;\n" % (name, json.dumps(character_class(values)))
    content += "const LOWER = new Map(Object.entries(%s));\n" % json.dumps(lower, ensure_ascii=True, separators=(",", ":"))
    content += '''const CASED = new RegExp(PYTHON_CASED_CLASS, 'u');
const IGNORABLE = new RegExp(PYTHON_CASE_IGNORABLE_CLASS, 'u');
export function pythonLower(value) {
  const chars = Array.from(value);
  return chars.map((char, index) => {
    if (char !== 'Σ') return LOWER.get(char) ?? char;
    let before = index - 1, after = index + 1;
    while (before >= 0 && IGNORABLE.test(chars[before])) before--;
    if (before < 0 || !CASED.test(chars[before])) return 'σ';
    while (after < chars.length && IGNORABLE.test(chars[after])) after++;
    return after === chars.length || !CASED.test(chars[after]) ? 'ς' : 'σ';
  }).join('');
}
'''
    target.write_text(content, encoding="utf-8")
    print(json.dumps({"target": str(target), "unicode": unicodedata.unidata_version,
                      "bytes": len(content.encode()), "lower_mappings": len(lower)}))


if __name__ == "__main__":
    main()
